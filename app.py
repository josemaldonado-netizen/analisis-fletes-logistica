# 2. MOTOR COMPARATIVO DE FLETES
# -----------------------------------------------------------------------------
def generar_comparativo_semanal(df_datos, sem_a, sem_b):
    df_a = df_datos[df_datos['SEMANA_ANALISIS'] == sem_a]
    df_b = df_datos[df_datos['SEMANA_ANALISIS'] == sem_b]

    conceptos = [
        'FLETE FACTURA',
        'MANIOBRAS',
        'REPARTOS',
        'DEMORAS Y ESTADIAS',
        'OTROS',
        'TOTAL FLETE'
    ]

    filas = []
    for conc in conceptos:
        m_a = df_a[conc].sum() if conc in df_a.columns else 0.0
        m_b = df_b[conc].sum() if conc in df_b.columns else 0.0
        dif = m_b - m_a

        # Corrección de variación para evitar +0.0% cuando m_a es 0
        if m_a > 0:
            pct = ((m_b - m_a) / m_a) * 100
            str_pct = f"{pct:+.1f}%"
        elif m_b > 0:
            str_pct = "+100.0% (NUEVO)"
        else:
            str_pct = "+0.0%"

        filas.append({
            'Línea de Gasto': conc,
            f'Semana {sem_a}': f"${m_a:,.2f}",
            f'Semana {sem_b}': f"${m_b:,.2f}",
            'Diferencia ($)': f"${dif:,.2f}",
            'Variación (%)': str_pct
        })

    # Métricas de Costo por KG y Costo por Tarima
    kg_a = df_a['KG MOVIDOS'].sum() if 'KG MOVIDOS' in df_a.columns else 0
    kg_b = df_b['KG MOVIDOS'].sum() if 'KG MOVIDOS' in df_b.columns else 0

    col_tarimas = 'TARIMAS TOTALES POR VIAJE' if 'TARIMAS TOTALES POR VIAJE' in df_a.columns else 'TARIMAS'
    tar_a = df_a[col_tarimas].sum() if col_tarimas in df_a.columns else 0
    tar_b = df_b[col_tarimas].sum() if col_tarimas in df_b.columns else 0

    tot_a = df_a['TOTAL FLETE'].sum() if 'TOTAL FLETE' in df_a.columns else 0
    tot_b = df_b['TOTAL FLETE'].sum() if 'TOTAL FLETE' in df_b.columns else 0

    c_kg_a = (tot_a / kg_a) if kg_a > 0 else 0.0
    c_kg_b = (tot_b / kg_b) if kg_b > 0 else 0.0

    c_t_a = (tot_a / tar_a) if tar_a > 0 else 0.0
    c_t_b = (tot_b / tar_b) if tar_b > 0 else 0.0

    dif_kg = c_kg_b - c_kg_a
    dif_t = c_t_b - c_t_a

    return pd.DataFrame(filas), c_kg_b, dif_kg, c_t_b, dif_t