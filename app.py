def auditoria_y_comparativo_profundo(df_datos, sem_a=2, sem_b=3):
    # 1. Filtrar semanas
    df_a = df_datos[df_datos['SEMANA_ANALISIS'] == sem_a].copy()
    df_b = df_datos[df_datos['SEMANA_ANALISIS'] == sem_b].copy()

    # 2. Métricas Estadísticas Base (Semana A vs Semana B)
    media_total_a = df_a['TOTAL FLETE'].mean()
    media_total_b = df_b['TOTAL FLETE'].mean()

    media_flete_a = df_a['FLETE FACTURA'].mean()
    media_flete_b = df_b['FLETE FACTURA'].mean()

    # 3. Impresión del Resumen Estadístico
    print("=" * 75)
    print(f"📊 DIAGNÓSTICO ESTADÍSTICO OPERATIVO: SEMANA {sem_a} VS SEMANA {sem_b}")
    print("=" * 75)
    print(f"🔹 Viajes Realizados:               Semana {sem_a}: {len(df_a)} viajes  |  Semana {sem_b}: {len(df_b)} viajes")
    print(f"📐 Promedio Costo/Viaje (TOTAL):    Semana {sem_a}: ${media_total_a:,.2f}  |  Semana {sem_b}: ${media_total_b:,.2f}")
    print(f"📐 Promedio Flete Factura/Viaje:    Semana {sem_a}: ${media_flete_a:,.2f}  |  Semana {sem_b}: ${media_flete_b:,.2f}")

    # 4. DETECCIÓN DE VIAJES ATÍPICOS EN LA SEMANA B (Mayores a la Media de Semana A)
    # Buscamos viajes en Semana B que superen el promedio de la Semana A
    viajes_altos = df_b[df_b['TOTAL FLETE'] > media_total_a].copy()
    viajes_altos['Diferencia vs Media A'] = viajes_altos['TOTAL FLETE'] - media_total_a

    # Ordenar de mayor a menor costo
    viajes_altos = viajes_altos.sort_values(by='TOTAL FLETE', ascending=False)

    print("\n" + "=" * 75)
    print(f"🚨 AUDITORÍA DE ANOMALÍAS: {len(viajes_altos)} VIAJES EN SEMANA {sem_b} SUPERAN LA MEDIA DE LA SEMANA {sem_a} (${media_total_a:,.2f})")
    print("=" * 75)

    cols_detalle = ['MES_ORIGEN', 'CLIENTE', 'TRANSPORTISTA', 'CIUDAD DESTINO', 'FLETE FACTURA', 'DEMORAS Y ESTADIAS', 'TOTAL FLETE', 'Diferencia vs Media A']
    cols_existentes = [c for c in cols_detalle if c in viajes_altos.columns]

    if len(viajes_altos) > 0:
        # Formatear moneda para visualización limpia
        df_show = viajes_altos[cols_existentes].head(10).copy() # Mostramos los 10 principales
        for c in ['FLETE FACTURA', 'DEMORAS Y ESTADIAS', 'TOTAL FLETE', 'Diferencia vs Media A']:
            if c in df_show.columns:
                df_show[c] = df_show[c].apply(lambda x: f"${x:,.2f}")

        display(df_show)
    else:
        print("✅ No se detectaron viajes con costos por encima de la media de la semana base.")

# Probar la auditoría profunda entre semanas (ejemplo Semana 2 vs Semana 3)
auditoria_y_comparativo_profundo(df, sem_a=2, sem_b=3)

