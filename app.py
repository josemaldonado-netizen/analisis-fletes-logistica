def limpiar_columnas_numericas(df_in):
    df_clean = df_in.copy()

    # Columnas que deben ser numéricas
    cols_moneda = ['TOTAL FLETE', 'COSTO POR TARIMA', 'DEMORAS Y ESTADIAS', 'TARIMA', 'TARIMAS']

    for col in cols_moneda:
        if col in df_clean.columns:
            # Convertir a texto primero por seguridad
            s = df_clean[col].astype(str)
            # Limpiar símbolos $, comas y espacios
            s = s.str.replace('$', '', regex=False)\
                 .str.replace(',', '', regex=False)\
                 .str.replace(' ', '', regex=False)\
                 .str.strip()
            # Convertir a flotante (lo que no sea número se vuelve NaN y luego 0)
            df_clean[col] = pd.to_numeric(s, errors='coerce').fillna(0)

    return df_clean

