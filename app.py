import streamlit as st
import pandas as pd
import numpy as np

st.set_page_config(page_title="LogiSense AI", layout="wide")
st.title("🚚 LogiSense AI — Analítica Logística Avanzada")

# 1. Componente para subir el archivo (Excel o CSV)
archivo_subido = st.file_uploader(
    "📁 Carga tu archivo de datos (Excel .xlsx o CSV)",
    type=["xlsx", "csv"]
)

CONFIG_HOJAS = {
    'ENERO': 430,
    'FEBRERO': 408,
    'MARZO': 370,
    'ABRIL': 662,
    'MAYO': 394,
    'JUNIO': 398,
    'JULIO': 387
}

@st.cache_data
def procesar_archivo(file):
    lista_dfs = []

    if file.name.endswith('.xlsx'):
        excel_file = pd.ExcelFile(file)
        for nombre_hoja, limite_fila in CONFIG_HOJAS.items():
            if nombre_hoja in excel_file.sheet_names:
                df_temp = pd.read_excel(excel_file, sheet_name=nombre_hoja, nrows=limite_fila, header=0)
                if not df_temp.empty:
                    df_temp.columns = [str(h).strip() for h in df_temp.columns]
                    df_temp['MES_ORIGEN'] = nombre_hoja
                    lista_dfs.append(df_temp)
    else:
        df_temp = pd.read_csv(file, header=0)
        df_temp.columns = [str(h).strip() for h in df_temp.columns]
        lista_dfs.append(df_temp)

    if not lista_dfs:
        return pd.DataFrame()

    df_out = pd.concat(lista_dfs, ignore_index=True)

    # Asignar la semana
    col_sem = 'SEMANA CALENDARIO FACTURA' if 'SEMANA CALENDARIO FACTURA' in df_out.columns else 'SEMANA CALENDARIO PEDIDO'
    if col_sem in df_out.columns:
        df_out['SEMANA_ANALISIS'] = pd.to_numeric(df_out[col_sem], errors='coerce')

    if 'MES FACTURA' not in df_out.columns:
        df_out['MES FACTURA'] = df_out['MES_ORIGEN']

    # Limpieza de montos financieros y volumétricos
    cols_a_limpiar = [
        'IMPORTE FACTURADO SIN IVA', 'KG MOVIDOS', 'FLETE FACTURA',
        'MANIOBRAS', 'REPARTOS', 'DEMORAS Y ESTADIAS', 'OTROS',
        'TOTAL FLETE', 'KM RECORRIDOS', 'TARIMAS TOTALES POR VIAJE'
    ]

    for c in cols_a_limpiar:
        if c in df_out.columns:
            df_out[c] = df_out[c].astype(str).str.replace('$', '', regex=False).str.replace(',', '', regex=False).str.strip()
            df_out[c] = pd.to_numeric(df_out[c], errors='coerce').fillna(0)

    # CONSOLIDACIÓN DE EMBARQUES / VIAJES
    if 'EMBARQUE' in df_out.columns:
        df_out['EMBARQUE_CLEAN'] = df_out['EMBARQUE'].astype(str).str.strip().str.upper()

        id_viajes = []
        contador_na = 0
        for idx, row in df_out.iterrows():
            emb = row['EMBARQUE_CLEAN']
            flete = row['TOTAL FLETE']

            if emb not in ['NA', 'NAN', '', 'NONE', '0']:
                id_viajes.append(f"EMB_{emb}")
            else:
                if flete > 0:
                    contador_na += 1
                    id_viajes.append(f"VIAJE_NA_{contador_na}")
                else:
                    id_viajes.append("IGNORAR_VIAJE")

        df_out['ID_VIAJE_UNICO'] = id_viajes
    else:
        df_out['ID_VIAJE_UNICO'] = df_out.index.astype(str)

    return df_out

# Carga y procesamiento del archivo
if archivo_subido is not None:
    with st.spinner("⏳ Procesando datos del archivo..."):
        df_raw = procesar_archivo(archivo_subido)

    if not df_raw.empty:
        st.success("✅ Base de datos cargada y consolidada por viajes correctamente.")

        # ---------------------------------------------------------
        # BARRA LATERAL: FILTROS DE ANÁLISIS
        # ---------------------------------------------------------
        st.sidebar.header("🔍 Filtros Operativos")

        col_embarque = 'TIPO DE EMBARQUE'
        opciones_embarque = ["Todos"] + sorted([str(x) for x in df_raw[col_embarque].dropna().unique()]) if col_embarque in df_raw.columns else ["Todos"]
        embarque_sel = st.sidebar.selectbox("Tipo de Embarque (TR1, TR2, etc.)", opciones_embarque)

        col_cliente = 'CLIENTE'
        opciones_cliente = sorted([str(x) for x in df_raw[col_cliente].dropna().unique()]) if col_cliente in df_raw.columns else []
        clientes_sel = st.sidebar.multiselect("Cliente(s)", opciones_cliente, default=[])

        col_transp = 'TRANSPORTISTA'
        opciones_transp = sorted([str(x) for x in df_raw[col_transp].dropna().unique()]) if col_transp in df_raw.columns else []
        transp_sel = st.sidebar.multiselect("Transportista(s)", opciones_transp, default=[])

        col_tipo_trans = 'TIPO DE TRANSPORTE'
        opciones_tipo_trans = ["Todos"] + sorted([str(x) for x in df_raw[col_tipo_trans].dropna().unique()]) if col_tipo_trans in df_raw.columns else ["Todos"]
        tipo_trans_sel = st.sidebar.selectbox("Tipo de Transporte", opciones_tipo_trans)

        # Aplicar filtros
        df = df_raw.copy()
        if embarque_sel != "Todos" and col_embarque in df.columns:
            df = df[df[col_embarque].astype(str) == embarque_sel]
        if clientes_sel and col_cliente in df.columns:
            df = df[df[col_cliente].astype(str).isin(clientes_sel)]
        if transp_sel and col_transp in df.columns:
            df = df[df[col_transp].astype(str).isin(transp_sel)]
        if tipo_trans_sel != "Todos" and col_tipo_trans in df.columns:
            df = df[df[col_tipo_trans].astype(str) == tipo_trans_sel]

        # ---------------------------------------------------------
        # SELECCIÓN DE PERIODO
        # ---------------------------------------------------------
        st.sidebar.markdown("---")
        st.sidebar.header("📅 Periodos de Comparación")
        modo_periodo = st.sidebar.radio("Comparar por:", ["Semana", "Mes"])

        if modo_periodo == "Semana":
            col_periodo = 'SEMANA_ANALISIS'
            periodos = sorted([int(x) for x in df[col_periodo].dropna().unique()])
            label_a, label_b = "Semana A (Base)", "Semana B (Actual)"
        else:
            col_periodo = 'MES FACTURA'
            periodos = sorted([str(x) for x in df[col_periodo].dropna().unique()])
            label_a, label_b = "Mes A (Base)", "Mes B (Actual)"

        if len(periodos) > 0:
            c_per1, c_per2 = st.sidebar.columns(2)
            per_a = c_per1.selectbox(label_a, periodos, index=0)
            per_b = c_per2.selectbox(label_b, periodos, index=min(1, len(periodos)-1))

            df_a = df[df[col_periodo] == per_a]
            df_b = df[df[col_periodo] == per_b]

            # ---------------------------------------------------------
            # TABS DE VISUALIZACIÓN
            # ---------------------------------------------------------
            tab1, tab2, tab3 = st.tabs(["📊 Comparativo Financiero y Medias", "🚨 Auditoría de Anomalías", "📝 Prompt para IA Executive"])

            with tab1:
                st.subheader(f"📊 Comparativa Real: {modo_periodo} {per_a} vs {modo_periodo} {per_b}")

                # CÁLCULOS
                df_a_viajes = df_a[df_a['ID_VIAJE_UNICO'] != 'IGNORAR_VIAJE']
                df_b_viajes = df_b[df_b['ID_VIAJE_UNICO'] != 'IGNORAR_VIAJE']

                viajes_a = df_a_viajes['ID_VIAJE_UNICO'].nunique()
                viajes_b = df_b_viajes['ID_VIAJE_UNICO'].nunique()

                tot_a = df_a['TOTAL FLETE'].sum() if 'TOTAL FLETE' in df_a.columns else 0
                tot_b = df_b['TOTAL FLETE'].sum() if 'TOTAL FLETE' in df_b.columns else 0

                media_viaje_a = (tot_a / viajes_a) if viajes_a > 0 else 0
                media_viaje_b = (tot_b / viajes_b) if viajes_b > 0 else 0

                # Sumatorias de KGs y Tarimas
                kg_a = df_a['KG MOVIDOS'].sum() if 'KG MOVIDOS' in df_a.columns else 0
                kg_b = df_b['KG MOVIDOS'].sum() if 'KG MOVIDOS' in df_b.columns else 0

                tar_a = df_a['TARIMAS TOTALES POR VIAJE'].sum() if 'TARIMAS TOTALES POR VIAJE' in df_a.columns else 0
                tar_b = df_b['TARIMAS TOTALES POR VIAJE'].sum() if 'TARIMAS TOTALES POR VIAJE' in df_b.columns else 0

                # TARJETAS DE INDICADORES (KPIs)
                st.markdown("### 📐 Resumen de Indicadores Clave")
                m_col1, m_col2, m_col3, m_col4 = st.columns(4)

                with m_col1:
                    st.metric(
                        label=f"Total Viajes ({modo_periodo} {per_a} ➜ {per_b})",
                        value=f"{viajes_a} ➜ {viajes_b}",
                        delta=f"{viajes_b - viajes_a} viajes"
                    )

                with m_col2:
                    var_viaje = ((media_viaje_b - media_viaje_a) / media_viaje_a * 100) if media_viaje_a > 0 else 0
                    st.metric(
                        label=f"Costo Medio / Viaje ({modo_periodo} {per_a} ➜ {per_b})",
                        value=f"${media_viaje_a:,.2f} ➜ ${media_viaje_b:,.2f}",
                        delta=f"{var_viaje:+.1f}%"
                    )

                with m_col3:
                    var_kg = ((kg_b - kg_a) / kg_a * 100) if kg_a > 0 else 0
                    st.metric(
                        label=f"KG Movidos ({modo_periodo} {per_a} ➜ {per_b})",
                        value=f"{kg_a:,.0f} kg ➜ {kg_b:,.0f} kg",
                        delta=f"{var_kg:+.1f}%"
                    )

                with m_col4:
                    var_tar = ((tar_b - tar_a) / tar_a * 100) if tar_a > 0 else 0
                    st.metric(
                        label=f"Tarimas Totales ({modo_periodo} {per_a} ➜ {per_b})",
                        value=f"{tar_a:,.0f} ➜ {tar_b:,.0f}",
                        delta=f"{var_tar:+.1f}%"
                    )

                st.markdown("---")
                st.markdown("### 💵 Desglose de Gastos Acumulados")

                conceptos = ['FLETE FACTURA', 'MANIOBRAS', 'REPARTOS', 'DEMORAS Y ESTADIAS', 'OTROS', 'TOTAL FLETE']
                filas = []
                for conc in conceptos:
                    m_a = df_a[conc].sum() if conc in df_a.columns else 0
                    m_b = df_b[conc].sum() if conc in df_b.columns else 0
                    dif = m_b - m_a
                    pct = ((m_b - m_a) / m_a * 100) if m_a > 0 else 0

                    filas.append({
                        'Línea de Gasto': conc,
                        f'{modo_periodo} {per_a}': f"${m_a:,.2f}",
                        f'{modo_periodo} {per_b}': f"${m_b:,.2f}",
                        'Diferencia ($)': f"${dif:,.2f}",
                        'Variación (%)': f"{pct:+.1f}%"
                    })
                st.table(pd.DataFrame(filas))

            # TAB 2: AUDITORÍA AGRUPADA POR VIAJE
            with tab2:
                df_b_grouped = df_b.groupby('ID_VIAJE_UNICO').agg({
                    'EMBARQUE': 'first',
                    'CLIENTE': 'first',
                    'TRANSPORTISTA': 'first',
                    'LOCALIDAD': 'first',
                    'TIPO DE TRANSPORTE': 'first',
                    'KG MOVIDOS': 'sum',
                    'TARIMAS TOTALES POR VIAJE': 'sum',
                    'KM RECORRIDOS': 'max',
                    'FLETE FACTURA': 'sum',
                    'DEMORAS Y ESTADIAS': 'sum',
                    'TOTAL FLETE': 'sum'
                }).reset_index()

                media_ref = media_viaje_a
                viajes_altos = df_b_grouped[df_b_grouped['TOTAL FLETE'] > media_ref].copy()

                if not viajes_altos.empty:
                    viajes_altos['Diferencia vs Media Base'] = viajes_altos['TOTAL FLETE'] - media_ref
                    viajes_altos = viajes_altos.sort_values(by='TOTAL FLETE', ascending=False)

                    st.warning(f"🚨 Auditoría: **{len(viajes_altos)} embarques/viajes consolidados** en el {modo_periodo} {per_b} superan el costo promedio por viaje del {modo_periodo} {per_a} (${media_ref:,.2f})")
                    st.dataframe(viajes_altos, use_container_width=True)
                else:
                    st.success(f"✅ No se encontraron embarques consolidados en el {modo_periodo} {per_b} que superen la media del {modo_periodo} {per_a}.")

            # TAB 3: PROMPT GENERATOR
            with tab3:
                var_tot = ((tot_b - tot_a) / tot_a * 100) if tot_a > 0 else 0

                prompt_texto = f"""Actúa como un Gerente Senior de Logística y Cadena de Suministro.
Analiza la siguiente variación de fletes e imprevistos financieros y genera un reporte ejecutivo.

DATOS COMPARATIVOS ({modo_periodo.upper()} {per_a} vs {modo_periodo.upper()} {per_b}):
- Periodo Base ({modo_periodo} {per_a}): Viajes Reales: {viajes_a} | KG Movidos: {kg_a:,.0f} | Tarimas: {tar_a:,.0f} | Gasto Total: ${tot_a:,.2f} | Costo Medio/Viaje: ${media_viaje_a:,.2f}
- Periodo Actual ({modo_periodo} {per_b}): Viajes Reales: {viajes_b} | KG Movidos: {kg_b:,.0f} | Tarimas: {tar_b:,.0f} | Gasto Total: ${tot_b:,.2f} | Costo Medio/Viaje: ${media_viaje_b:,.2f}
- Variación del Gasto Total: {var_tot:+.2f}%
- Filtros Operativos -> Embarque: {embarque_sel} | Cliente: {clientes_sel if clientes_sel else 'Todos'} | Transportista: {transp_sel if transp_sel else 'Todos'}

ESTRUCTURA DEL REPORTE SOLICITADA:
1. 📌 Resumen Ejecutivo
2. 🚨 Alertas Operativas (Desviación en Costo por Viaje y Volumen)
3. 💡 Recomendaciones para Negociación y Eficiencia"""

                st.code(prompt_texto, language="markdown")
        else:
            st.error("No hay suficiente información para comparar con los filtros seleccionados.")
else:
    st.info("👆 Por favor sube tu archivo Excel o CSV para comenzar el análisis.")