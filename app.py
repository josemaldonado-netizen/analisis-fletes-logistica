def simular_chat_fletes(df_datos, pregunta):
    query = pregunta.lower()

    print(f"👤 Usuario: {pregunta}")
    print("-" * 60)

    # Consulta 1: Costo por tarima
    if "tarima" in query or "costo por tarima" in query:
        if 'COSTO POR TARIMA' in df_datos.columns and 'TRANSPORTISTA' in df_datos.columns:
            # Agrupar y calcular promedio en valores numéricos limpios
            agrupado = df_datos.groupby('TRANSPORTISTA')['COSTO POR TARIMA'].mean()
            top_transp = agrupado.idxmax()
            max_costo = agrupado.max()
            print(f"🤖 Asistente: 🚛 El transportista con el costo por tarima promedio más alto es {top_transp} con ${max_costo:,.2f} por tarima.")
        else:
            print("🤖 Asistente: ⚠️ No se encontró la columna 'COSTO POR TARIMA' o 'TRANSPORTISTA'.")

    # Consulta 2: Demoras y estadías
    elif "demora" in query or "estadía" in query or "estadia" in query or "tardía" in query:
        if 'DEMORAS Y ESTADIAS' in df_datos.columns:
            df_demoras = df_datos[df_datos['DEMORAS Y ESTADIAS'] > 0]
            tot_demoras = df_demoras['DEMORAS Y ESTADIAS'].sum()
            num_viajes = len(df_demoras)
            print(f"🤖 Asistente: 🚨 Se registraron {num_viajes} viajes con demoras/estadías, sumando un sobrecosto de ${tot_demoras:,.2f}.")
        else:
            print("🤖 Asistente: ⚠️ No se encontró la columna 'DEMORAS Y ESTADIAS'.")

    # Consulta 3: Volumen total de viajes
    elif "viaje" in query or "total" in query or "cuanto" in query:
        total_v = len(df_datos)
        gasto_total = df_datos['TOTAL FLETE'].sum() if 'TOTAL FLETE' in df_datos.columns else 0
        print(f"🤖 Asistente: 📊 Se registran {total_v} viajes totales con un gasto acumulado de ${gasto_total:,.2f}.")

    else:
        print("🤖 Asistente: Intenta preguntar sobre: 'costo por tarima', 'demoras' o 'total de viajes'.")
    print("=" * 60)

