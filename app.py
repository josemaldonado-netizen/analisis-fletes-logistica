# 1. FUNCIÓN DE LIMPIEZA DE DATOS
# ==========================================
def limpiar_columnas_numericas(df_in):
    df_clean = df_in.copy()
    cols_moneda = [
        'IMPORTE FACTURADO SIN IVA', 'KG MOVIDOS', 'FLETE FACTURA',
        'MANIOBRAS', 'REPARTOS', 'DEMORAS Y ESTADIAS', 'OTROS',
        'TOTAL FLETE', 'KM RECORRIDOS', 'TARIMAS TOTALES POR VIAJE',
        'COSTO POR TARIMA', 'TARIMA', 'TARIMAS'
    ]
    for col in cols_moneda:
        if col in df_clean.columns:
            s = df_clean[col].astype(str).str.replace('$', '', regex=False)\
                                         .str.replace(',', '', regex=False)\
                                         .str.replace(' ', '', regex=False)\
                                         .str.strip()
            df_clean[col] = pd.to_numeric(s, errors='coerce').fillna(0)

    # Asignar columna de semana para análisis
    if 'SEMANA_ANALISIS' not in df_clean.columns:
        col_sem = 'SEMANA CALENDARIO FACTURA' if 'SEMANA CALENDARIO FACTURA' in df_clean.columns else 'SEMANA CALENDARIO PEDIDO'
        if col_sem in df_clean.columns:
            df_clean['SEMANA_ANALISIS'] = pd.to_numeric(df_clean[col_sem], errors='coerce')
        else:
            df_clean['SEMANA_ANALISIS'] = 1

    return df_clean

