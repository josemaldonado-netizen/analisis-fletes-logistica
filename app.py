def ejecutar_comparativo_final(df_datos, sem_a=2, sem_b=3):
    df_a = df_datos[df_datos['SEMANA_ANALISIS'] == sem_a]
    df_b = df_datos[df_datos['SEMANA_ANALISIS'] == sem_b]

    conceptos = [
        'FLETE FACTURA',
        'MANIOBRAS',
        'REPARTOS',
        'DEMORAS Y ESTADIAS',
        'OTROS',
        'TOTAL FLETE'
    ]

    filas = []
    for conc in conceptos:
        m_a = df_a[conc].sum() if conc in df_a.columns else 0
        m_b = df_b[conc].sum() if conc in df_b.columns else 0
        dif = m_b - m_a
        pct = ((m_b - m_a) / m_a * 100) if m_a > 0 else 0

        filas.append({
            'Línea de Gasto': conc,
            f'Semana {sem_a}': f"${m_a:,.2f}",
            f'Semana {sem_b}': f"${m_b:,.2f}",
            'Diferencia ($)': f"${dif:,.2f}",
            'Variación (%)': f"{pct:+.1f}%"
        })

    kg_a = df_a['KG MOVIDOS'].sum() if 'KG MOVIDOS' in df_a.columns else 0
    kg_b = df_b['KG MOVIDOS'].sum() if 'KG MOVIDOS' in df_b.columns else 0

    tar_a = df_a['TARIMAS TOTALES POR VIAJE'].sum() if 'TARIMAS TOTALES POR VIAJE' in df_a.columns else 0
    tar_b = df_b['TARIMAS TOTALES POR VIAJE'].sum() if 'TARIMAS TOTALES POR VIAJE' in df_b.columns else 0

    tot_a = df_a['TOTAL FLETE'].sum() if 'TOTAL FLETE' in df_a.columns else 0
    tot_b = df_b['TOTAL FLETE'].sum() if 'TOTAL FLETE' in df_b.columns else 0

    c_kg_a = (tot_a / kg_a) if kg_a > 0 else 0
    c_kg_b = (tot_b / kg_b) if kg_b > 0 else 0

    c_t_a = (tot_a / tar_a) if tar_a > 0 else 0
    c_t_b = (tot_b / tar_b) if tar_b > 0 else 0

    print("=" * 65)
    print(f"📊 MOTOR COMPARATIVO REAL: SEMANA {sem_a} VS SEMANA {sem_b}")
    print("=" * 65)
    print(f"⚖️ Costo / KG:     Semana {sem_a}: ${c_kg_a:,.2f}  --->  Semana {sem_b}: ${c_kg_b:,.2f}")
    print(f"🪵 Costo / Tarima: Semana {sem_a}: ${c_t_a:,.2f}  --->  Semana {sem_b}: ${c_t_b:,.2f}")
    print("=" * 65)
    display(pd.DataFrame(filas))

