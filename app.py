def procesar_y_limpiar_dataframe(df_in):
    df_clean = df_in.copy()

    # Normalización de encabezados (quita espacios extra al inicio/final)
    df_clean.columns = [str(h).strip() for h in df_clean.columns]

    # Asignación de la Semana de Análisis
    col_sem = (
        'SEMANA CALENDARIO FACTURA'
        if 'SEMANA CALENDARIO FACTURA' in df_clean.columns
        else 'SEMANA CALENDARIO PEDIDO'
    )
    if col_sem in df_clean.columns:
        df_clean['SEMANA_ANALISIS'] = pd.to_numeric(df_clean[col_sem], errors='coerce')
    else:
        df_clean['SEMANA_ANALISIS'] = 1

    # LISTA COMPLETA DE COLUMNAS A LIMPIAR (Tal como en tu código original)
    cols_a_limpiar = [
        'IMPORTE FACTURADO SIN IVA', 'KG MOVIDOS', 'FLETE FACTURA',
        'MANIOBRAS', 'REPARTOS', 'DEMORAS Y ESTADIAS', 'OTROS',
        'TOTAL FLETE', 'KM RECORRIDOS', 'TARIMAS TOTALES POR VIAJE',
        'COSTO POR TARIMA', 'TARIMA', 'TARIMAS'
    ]

    for c in cols_a_limpiar:
        if c in df_clean.columns:
            # Convertir a texto, limpiar $, comas y espacios ocultos
            s = df_clean[c].astype(str)\
                           .str.replace('$', '', regex=False)\
                           .str.replace(',', '', regex=False)\
                           .str.replace('\xa0', '', regex=False)\
                           .str.strip()
            df_clean[c] = pd.to_numeric(s, errors='coerce').fillna(0)

    return df_clean


